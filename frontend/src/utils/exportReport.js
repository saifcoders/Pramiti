/**
 * exportReport.js - Academic Report Export Utilities for AyurEval (COGNEXA).
 *
 * Supports:
 *  1. Markdown (.md) instant file download
 *  2. Raw Data (.json) instant file download
 *  3. Publication-Grade Print-to-PDF via styled print view (window.print)
 */

/**
 * Triggers a client-side file download of a string blob.
 */
function downloadBlob(content, filename, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Generates an academic Markdown string from a Verification Report.
 */
function generateVerificationMarkdown(report) {
  const query = report.query_or_source || 'Clinical Inquiry';
  const claims = report.claims || [];
  const limitations = report.limitations || [];
  const timestamp = new Date().toLocaleString();

  let md = `# AyurEval (COGNEXA) Verification Report\n\n`;
  md += `**Generated:** ${timestamp}  \n`;
  md += `**Inquiry / Context:** ${query}  \n`;
  md += `**Total Claims Evaluated:** ${claims.length}\n\n`;
  md += `---\n\n`;
  md += `## 1. Executive Summary\n\n${report.overall_summary || 'Verification completed.'}\n\n`;

  if (report.generated_answer) {
    md += `## 2. Generated Clinical Text\n\n> ${report.generated_answer.replace(/\n/g, '\n> ')}\n\n`;
  }

  md += `## 3. Claim-by-Claim Verification & Evidence\n\n`;
  claims.forEach((c, i) => {
    md += `### Claim ${c.claim_id || i + 1}: ${c.category || 'Evaluated'}\n\n`;
    md += `**Claim Statement:**\n> ${c.claim_text}\n\n`;
    if (c.classical_reference) md += `- **Classical Reference:** ${c.classical_reference}\n`;
    if (c.original_passage) md += `- **Original Shloka / Passage:**\n  \`\`\`sanskrit\n  ${c.original_passage}\n  \`\`\`\n`;
    if (c.commentary_note) md += `- **Traditional Commentary:** ${c.commentary_note}\n`;
    if (c.scientific_evidence) md += `- **Biomedical / Clinical Evidence:** ${c.scientific_evidence}\n`;
    if (c.reasoning) md += `- **Verification Reasoning:** ${c.reasoning}\n`;
    md += `\n`;
  });

  if (limitations.length > 0) {
    md += `---\n\n## 4. Audit Limitations\n\n`;
    limitations.forEach((l) => { md += `- ${l}\n`; });
    md += `\n`;
  }

  md += `---\n*Generated by AyurEval (COGNEXA) — Source-Aware Canonical Ayurveda Verification Framework.*\n`;
  return md;
}

/**
 * Generates Markdown from a Dual-Evidence Cross-Audit Report.
 */
function generateDualAuditMarkdown(report) {
  const query = report.query_or_source || 'Dual Cross-Audit';
  const claims = report.claims || [];
  const gradeSummary = report.grade_summary || {};
  const limitations = report.limitations || [];
  const timestamp = new Date().toLocaleString();

  let md = `# AyurEval (COGNEXA) Dual-Evidence Cross-Audit Report\n\n`;
  md += `**Generated:** ${timestamp}  \n`;
  md += `**Inquiry Context:** ${query}  \n`;
  md += `**Total Claims Evaluated:** ${claims.length}\n\n`;
  md += `---\n\n`;
  md += `## 1. Executive Synthesis\n\n${report.executive_summary || 'Dual cross-audit completed.'}\n\n`;

  md += `### Dual-Evidence Grade Breakdown\n\n`;
  Object.entries(gradeSummary).forEach(([grade, count]) => {
    md += `- **${grade}:** ${count} claim(s)\n`;
  });
  md += `\n`;

  if (report.input_text) {
    md += `## 2. Audited Statement\n\n> ${report.input_text.replace(/\n/g, '\n> ')}\n\n`;
  }

  md += `## 3. Claim-by-Claim Dual Evidence Analysis\n\n`;
  claims.forEach((c, i) => {
    const classical = c.classical_evidence || {};
    const bio = c.biomedical_evidence || {};

    md += `### Claim ${c.claim_id || i + 1}: ${c.dual_grade || 'Evaluated'} (Confidence: ${Math.round((c.confidence || 0) * 100)}%)\n\n`;
    md += `**Claim Statement:**\n> ${c.claim_text}\n\n`;

    md += `#### Classical Samhita Evidence:\n`;
    md += `- **Matched:** ${classical.matched ? 'Yes' : 'No'}\n`;
    if (classical.reference) md += `- **Reference:** ${classical.reference}\n`;
    if (classical.original_passage) md += `- **Passage:**\n  \`\`\`sanskrit\n  ${classical.original_passage}\n  \`\`\`\n`;
    if (classical.commentary_note) md += `- **Commentary:** ${classical.commentary_note}\n`;
    md += `- **Relevance Score:** ${(classical.relevance_score || 0).toFixed(2)}\n\n`;

    md += `#### Modern Biomedical Evidence (PubMed):\n`;
    md += `- **Matched:** ${bio.matched ? 'Yes' : 'No'}\n`;
    if (bio.pmid) md += `- **PMID:** ${bio.pmid}\n`;
    if (bio.title) md += `- **Study Title:** ${bio.title}\n`;
    if (bio.journal) md += `- **Journal / Year:** ${bio.journal} (${bio.pub_year || 'N/A'})\n`;
    if (bio.study_type) md += `- **Study Classification:** ${bio.study_type}\n`;
    if (bio.abstract_snippet) md += `- **Abstract Snippet:** ${bio.abstract_snippet}\n`;
    md += `- **Relevance Score:** ${(bio.relevance_score || 0).toFixed(2)}\n\n`;

    if (c.unified_reasoning) {
      md += `#### Unified Reasoning:\n${c.unified_reasoning}\n\n`;
    }
  });

  if (limitations.length > 0) {
    md += `---\n\n## 4. Audit Limitations\n\n`;
    limitations.forEach((l) => { md += `- ${l}\n`; });
    md += `\n`;
  }

  md += `---\n*Generated by AyurEval (COGNEXA) — Source-Aware Canonical Ayurveda Verification Framework.*\n`;
  return md;
}

/**
 * Generates Markdown from a Safety & Matra Report.
 */
function generateSafetyMarkdown(report) {
  const timestamp = new Date().toLocaleString();
  const isSafe = report.is_safe;
  const herbs = report.detected_herbs || [];
  const alerts = report.alerts || [];
  const profiles = report.profiles || {};

  let md = `# AyurEval (COGNEXA) Safety & Matra Audit Report\n\n`;
  md += `**Generated:** ${timestamp}  \n`;
  md += `**Safety Clearance Status:** **${isSafe ? 'SAFE FOR ADMINISTRATION' : 'CRITICAL HAZARD / CONTRAINDICATION DETECTED'}**  \n`;
  md += `**Detected Herbs:** ${herbs.join(', ') || 'None'}\n\n`;
  md += `---\n\n`;
  md += `## 1. Executive Safety Summary\n\n${report.summary || 'Safety evaluation completed.'}\n\n`;

  if (report.input_text) {
    md += `## 2. Audited Prescription / Query\n\n> ${report.input_text.replace(/\n/g, '\n> ')}\n\n`;
  }

  md += `## 3. Flagged Safety Alerts & Guidelines\n\n`;
  if (alerts.length > 0) {
    alerts.forEach((a, i) => {
      md += `### Alert ${i + 1}: [${a.severity}] ${a.alert_type} (${a.herb})\n\n`;
      md += `- **Finding:** ${a.message}\n`;
      md += `- **Actionable Guidance:** ${a.recommendation}\n`;
      if (a.classical_reference) md += `- **Source:** ${a.classical_reference}\n`;
      md += `\n`;
    });
  } else {
    md += `No contraindications or active safety hazards detected.\n\n`;
  }

  if (Object.keys(profiles).length > 0) {
    md += `## 4. Classical Matra (Dosage) & Anupana Pharmacology Profiles\n\n`;
    Object.values(profiles).forEach((p) => {
      md += `### ${p.herb_name} (*${p.botanical_name}*)\n\n`;
      md += `- **Classical Matra (Dosage):** ${p.classical_matra}\n`;
      md += `- **Max Daily Bound:** ${p.max_daily_matra}\n`;
      md += `- **Recommended Anupana:** ${(p.anupana || []).join(', ')}\n`;
      if (p.contraindications?.length) {
        md += `- **Known Contraindications:**\n`;
        p.contraindications.forEach((c) => { md += `  - ${c}\n`; });
      }
      if (p.herb_drug_interactions?.length) {
        md += `- **Herb-Drug Interactions:**\n`;
        p.herb_drug_interactions.forEach((d) => { md += `  - ${d}\n`; });
      }
      if (p.special_precautions) md += `- **Precaution:** ${p.special_precautions}\n`;
      if (p.classical_source) md += `- **Classical Source:** ${p.classical_source}\n`;
      md += `\n`;
    });
  }

  md += `---\n*Generated by AyurEval (COGNEXA) — Source-Aware Canonical Ayurveda Verification Framework.*\n`;
  return md;
}

/**
 * Generates Markdown from a Batch Verification Report.
 */
function generateBatchMarkdown(report) {
  const timestamp = new Date().toLocaleString();
  const analytics = report.analytics || {};
  const results = report.results || [];

  let md = `# AyurEval (COGNEXA) Batch Claim Verification Report\n\n`;
  md += `**Generated:** ${timestamp}  \n`;
  if (report.source_name) md += `**Source:** ${report.source_name}  \n`;
  md += `**Total Claims:** ${analytics.total_claims || results.length}\n\n`;
  md += `---\n\n`;
  md += `## 1. Analytics Summary\n\n`;
  md += `| Verdict | Count |\n|---------|-------|\n`;
  md += `| ✅ Supported | ${analytics.supported || 0} |\n`;
  md += `| 🟡 Partially Supported | ${analytics.partially_supported || 0} |\n`;
  md += `| 🔴 Contradicted | ${analytics.contradicted || 0} |\n`;
  md += `| ⚫ Insufficient Evidence | ${analytics.insufficient_evidence || 0} |\n`;
  md += `| ❓ Reference Not Verified | ${analytics.reference_not_verified || 0} |\n`;
  md += `| 🛡 Total Safety Flags | ${analytics.total_safety_flags || 0} |\n`;
  md += `| 🚨 Critical Safety Flags | ${analytics.critical_safety_flags || 0} |\n\n`;

  md += `## 2. Per-Claim Results\n\n`;
  results.forEach((r) => {
    md += `### Claim ${r.claim_index}: ${r.category}\n\n`;
    md += `**Statement:** ${r.claim_text}\n\n`;
    if (r.classical_reference) md += `- **Classical Reference:** ${r.classical_reference}\n`;
    if (r.reasoning) md += `- **Reasoning:** ${r.reasoning}\n`;
    md += `- **Safety:** ${r.is_safe ? '✅ Safe' : '⚠️ Safety Alert'}\n`;
    if (r.safety_alerts && r.safety_alerts.length > 0) {
      r.safety_alerts.forEach((a) => { md += `  - ${a}\n`; });
    }
    md += `\n`;
  });

  md += `---\n*Generated by AyurEval (COGNEXA) — Source-Aware Canonical Ayurveda Verification Framework.*\n`;
  return md;
}

/**
 * Export report as a Markdown (.md) file.
 */
export function exportReportMarkdown(reportType, report) {
  if (!report) return;
  let md = '';
  let filename = `AyurEval_${reportType}_${Date.now()}.md`;

  if (reportType === 'verification') {
    md = generateVerificationMarkdown(report);
  } else if (reportType === 'dual-audit') {
    md = generateDualAuditMarkdown(report);
  } else if (reportType === 'safety') {
    md = generateSafetyMarkdown(report);
  } else if (reportType === 'batch') {
    md = generateBatchMarkdown(report);
  } else {
    md = JSON.stringify(report, null, 2);
    filename = `AyurEval_Report_${Date.now()}.json`;
  }

  downloadBlob(md, filename, 'text/markdown;charset=utf-8');
}

/**
 * Export raw report data as a JSON (.json) file.
 */
export function exportReportJSON(reportType, report) {
  if (!report) return;
  const jsonStr = JSON.stringify(report, null, 2);
  const filename = `AyurEval_${reportType}_Data_${Date.now()}.json`;
  downloadBlob(jsonStr, filename, 'application/json;charset=utf-8');
}

