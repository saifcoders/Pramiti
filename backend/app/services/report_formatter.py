"""Report Formatting Utility for AyurEval (COGNEXA).

Formats verification, dual-evidence cross-audits, and safety/contraindication
reports into structured, publication-grade Markdown and academic text documents.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional


def format_verification_report_markdown(report: Dict[str, Any]) -> str:
    """Formats an AyurEval verification report into academic Markdown."""
    query = report.get("query_or_source", "Clinical Inquiry")
    generated = report.get("generated_answer", "")
    overall = report.get("overall_summary", "")
    claims: List[Dict[str, Any]] = report.get("claims", [])
    limitations: List[str] = report.get("limitations", [])
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # Count categories
    counts: Dict[str, int] = {}
    for c in claims:
        cat = c.get("category", "Unknown")
        counts[cat] = counts.get(cat, 0) + 1

    lines = [
        "# AyurEval (COGNEXA) Verification Report",
        "",
        f"**Date Generated:** {timestamp}  ",
        f"**Source / Inquiry:** {query}  ",
        f"**Total Claims Evaluated:** {len(claims)}",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        "",
        overall or "No executive summary provided.",
        "",
        "### Audit Verdict Breakdown",
        "",
    ]

    for cat, count in counts.items():
        lines.append(f"- **{cat}:** {count} claim(s)")

    if generated:
        lines.extend([
            "",
            "## 2. Generated Clinical Text",
            "",
            "> " + generated.replace("\n", "\n> "),
            "",
        ])

    lines.extend([
        "",
        "## 3. Claim-by-Claim Verification & Canonical Evidence",
        "",
    ])

    for i, claim in enumerate(claims, 1):
        cid = claim.get("claim_id", i)
        ctext = claim.get("claim_text", "")
        category = claim.get("category", "Unknown")
        ref = claim.get("classical_reference", "None cited")
        passage = claim.get("original_passage")
        commentary = claim.get("commentary_note")
        scientific = claim.get("scientific_evidence")
        reasoning = claim.get("reasoning")

        lines.extend([
            f"### Claim {cid}: {category}",
            "",
            f"**Claim Text:**  ",
            f"> {ctext}",
            "",
            f"- **Classical Reference:** {ref}",
        ])

        if passage:
            lines.extend([
                f"- **Original Shloka / Passage:**",
                f"  ```sanskrit",
                f"  {passage}",
                f"  ```",
            ])

        if commentary:
            lines.append(f"- **Traditional Commentary:** {commentary}")

        if scientific:
            lines.append(f"- **Scientific / Biomedical Evidence:** {scientific}")

        if reasoning:
            lines.append(f"- **Verification Reasoning:** {reasoning}")

        lines.append("")

    if limitations:
        lines.extend([
            "---",
            "",
            "## 4. Methodology & Audit Limitations",
            "",
        ])
        for lim in limitations:
            lines.append(f"- {lim}")

    lines.extend([
        "",
        "---",
        "*Report generated by AyurEval (COGNEXA) — Source-Aware Canonical Ayurveda Verification Framework.*",
    ])

    return "\n".join(lines)


def format_dual_audit_report_markdown(report: Dict[str, Any]) -> str:
    """Formats a Classical vs. Biomedical Dual-Evidence Cross-Audit report into Markdown."""
    query = report.get("query_or_source", "Dual Evidence Audit")
    input_text = report.get("input_text", "")
    executive = report.get("executive_summary", "")
    grade_summary = report.get("grade_summary", {})
    claims: List[Dict[str, Any]] = report.get("claims", [])
    limitations: List[str] = report.get("limitations", [])
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        "# AyurEval (COGNEXA) Dual-Evidence Cross-Audit Report",
        "",
        f"**Date Generated:** {timestamp}  ",
        f"**Audit Context:** {query}  ",
        f"**Total Claims Evaluated:** {len(claims)}",
        "",
        "---",
        "",
        "## 1. Executive Synthesis",
        "",
        executive or "Dual cross-audit completed.",
        "",
        "### Dual-Evidence Grade Summary",
        "",
    ]

    for grade, count in grade_summary.items():
        lines.append(f"- **{grade}:** {count} claim(s)")

    if input_text:
        lines.extend([
            "",
            "## 2. Audited Statement",
            "",
            "> " + input_text.replace("\n", "\n> "),
            "",
        ])

    lines.extend([
        "",
        "## 3. Claim-by-Claim Dual Evidence Analysis",
        "",
    ])

    for i, claim in enumerate(claims, 1):
        cid = claim.get("claim_id", i)
        ctext = claim.get("claim_text", "")
        grade = claim.get("dual_grade", "Unknown")
        conf = claim.get("confidence", 0.0)
        classical = claim.get("classical_evidence", {})
        bio = claim.get("biomedical_evidence", {})
        reasoning = claim.get("unified_reasoning", "")

        lines.extend([
            f"### Claim {cid}: {grade} (Confidence: {int(conf * 100)}%)",
            "",
            f"**Claim Statement:**  ",
            f"> {ctext}",
            "",
            "#### Classical Samhita Evidence:",
            f"- **Matched:** {'Yes' if classical.get('matched') else 'No'}",
            f"- **Reference:** {classical.get('reference') or 'None'}",
        ])

        if classical.get("original_passage"):
            lines.extend([
                f"- **Passage:**",
                f"  ```sanskrit",
                f"  {classical.get('original_passage')}",
                f"  ```",
            ])

        if classical.get("commentary_note"):
            lines.append(f"- **Commentary:** {classical.get('commentary_note')}")

        lines.append(f"- **Relevance Score:** {classical.get('relevance_score', 0.0):.2f}")

        lines.extend([
            "",
            "#### Modern Biomedical Evidence (PubMed):",
            f"- **Matched:** {'Yes' if bio.get('matched') else 'No'}",
            f"- **PMID:** {bio.get('pmid') or 'N/A'}",
            f"- **Study Title:** {bio.get('title') or 'N/A'}",
            f"- **Journal / Year:** {bio.get('journal') or 'N/A'} ({bio.get('pub_year') or 'N/A'})",
            f"- **Study Type:** {bio.get('study_type') or 'N/A'}",
            f"- **Abstract Snippet:** {bio.get('abstract_snippet') or 'N/A'}",
            f"- **Relevance Score:** {bio.get('relevance_score', 0.0):.2f}",
            "",
            "#### Unified Dual Reasoning:",
            reasoning or "No unified reasoning recorded.",
            "",
        ])

    if limitations:
        lines.extend([
            "---",
            "",
            "## 4. Audit Limitations",
            "",
        ])
        for lim in limitations:
            lines.append(f"- {lim}")

    lines.extend([
        "",
        "---",
        "*Report generated by AyurEval (COGNEXA) — Source-Aware Canonical Ayurveda Verification Framework.*",
    ])

    return "\n".join(lines)


def format_safety_report_markdown(report: Dict[str, Any]) -> str:
    """Formats an Ayurvedic Safety & Matra Audit report into Markdown."""
    input_text = report.get("input_text", "")
    is_safe = report.get("is_safe", True)
    summary = report.get("summary", "")
    detected_herbs = report.get("detected_herbs", [])
    alerts: List[Dict[str, Any]] = report.get("alerts", [])
    profiles: Dict[str, Dict[str, Any]] = report.get("profiles", {})
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    status_str = "SAFE FOR ADMINISTRATION" if is_safe else "CRITICAL CONTRAINDICATION / TOXICITY HAZARD DETECTED"

    lines = [
        "# AyurEval (COGNEXA) Safety & Matra Audit Report",
        "",
        f"**Date Generated:** {timestamp}  ",
        f"**Overall Safety Verdict:** **{status_str}**  ",
        f"**Detected Herbs / Formulations:** {', '.join(detected_herbs) if detected_herbs else 'None'}",
        "",
        "---",
        "",
        "## 1. Executive Safety Summary",
        "",
        summary or "Safety audit completed.",
        "",
    ]

    if input_text:
        lines.extend([
            "## 2. Audited Prescription / Query",
            "",
            "> " + input_text.replace("\n", "\n> "),
            "",
        ])

    lines.extend([
        "## 3. Flagged Safety Alerts & Guidelines",
        "",
    ])

    if alerts:
        for i, a in enumerate(alerts, 1):
            sev = a.get("severity", "ADVISORY")
            atype = a.get("alert_type", "Alert")
            herb = a.get("herb", "")
            msg = a.get("message", "")
            rec = a.get("recommendation", "")
            ref = a.get("classical_reference")

            lines.extend([
                f"### Alert {i}: [{sev}] {atype} ({herb})",
                "",
                f"- **Clinical Finding:** {msg}",
                f"- **Recommendation / Action:** {rec}",
            ])
            if ref:
                lines.append(f"- **Canonical Reference:** {ref}")
            lines.append("")
    else:
        lines.append("No active contraindications or toxicity hazards identified.\n")

    if profiles:
        lines.extend([
            "## 4. Classical Matra (Dosage) & Anupana Pharmacology Profiles",
            "",
        ])
        for herb, p in profiles.items():
            lines.extend([
                f"### {herb} (*{p.get('botanical_name', '')}*)",
                "",
                f"- **Classical Matra (Dosage):** {p.get('classical_matra', 'N/A')}",
                f"- **Maximum Daily Bound:** {p.get('max_daily_matra', 'N/A')}",
                f"- **Recommended Anupana (Adjuvants):** {', '.join(p.get('anupana', []))}",
            ])
            if p.get("contraindications"):
                lines.append("- **Known Contraindications:**")
                for c in p.get("contraindications", []):
                    lines.append(f"  - {c}")
            if p.get("herb_drug_interactions"):
                lines.append("- **Herb-Drug Interactions:**")
                for d in p.get("herb_drug_interactions", []):
                    lines.append(f"  - {d}")
            if p.get("special_precautions"):
                lines.append(f"- **Special Precaution:** {p.get('special_precautions')}")
            if p.get("classical_source"):
                lines.append(f"- **Classical Reference:** {p.get('classical_source')}")
            lines.append("")

    lines.extend([
        "---",
        "*Report generated by AyurEval (COGNEXA) — Source-Aware Canonical Ayurveda Verification Framework.*",
    ])

    return "\n".join(lines)
